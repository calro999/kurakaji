def update_article(filepath, items_data):
    if not os.path.exists(filepath):
        print(f"File not found: {filepath}")
        return False
        
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
        
    # Find all product-item-card articles
    card_pattern = r'(<article class="product-item-card".*?</article>)'
    cards = re.findall(card_pattern, content, flags=re.DOTALL)
    
    if len(cards) != 7:
        print(f"Warning: {filepath} has {len(cards)} cards instead of 7!")
        return False
        
    for idx, card in enumerate(cards):
        data = items_data[idx]
        
        # Replace the <p style="color: #475569; font-size: 0.95rem; line-height: 1.7; margin-bottom: 16px;">...</p>
        # with an enriched editorial block
        old_p_pattern = r'<p style="color: #475569; font-size: 0.95rem; line-height: 1.7; margin-bottom: 16px;">.*?</p>'
        
        new_text = f"""<p style="color: #0f172a; font-size: 0.98rem; font-weight: 700; line-height: 1.5; margin-bottom: 8px;">{data['catch']}</p>
              <p style="color: #334155; font-size: 0.92rem; line-height: 1.75; margin-bottom: 16px;">{data['review']}</p>"""
              
        new_card = re.sub(old_p_pattern, new_text, card, count=1, flags=re.DOTALL)
        content = content.replace(card, new_card)
        
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
        
    print(f"SUCCESS: Enriched {filepath} with high-persuasion editorial reviews!")
    return True

