def update_ranking_card_file(fpath, data_list):
    with open(fpath, 'r', encoding='utf-8') as fp:
        html = fp.read()
    
    # find all ranking-card articles
    cards = re.findall(r'(<article class="ranking-card".*?</article>)', html, flags=re.DOTALL)
    if len(cards) != len(data_list):
        print(f"Error: {fpath} card count {len(cards)} != {len(data_list)}")
        return
        
    for idx, card in enumerate(cards):
        d = data_list[idx]
        # Replace the paragraph and evaluation box with concern-melting copy
        # Pattern to replace paragraph
        p_pattern = r'<p style="font-size: 0.95rem; color: #334155; line-height: 1.7; margin-bottom: 20px;">.*?</p>'
        new_p = f"""<p style="font-size: 0.98rem; font-weight: 700; color: #0f172a; line-height: 1.5; margin-bottom: 8px;">{d['catch']}</p>
              <p style="font-size: 0.92rem; color: #334155; line-height: 1.75; margin-bottom: 16px;">{d['review']}</p>"""
              
        new_card = re.sub(p_pattern, new_p, card, count=1, flags=re.DOTALL)
        html = html.replace(card, new_card)
        
    with open(fpath, 'w', encoding='utf-8') as fp:
        fp.write(html)
    print(f"SUCCESS: Updated {fpath}")

